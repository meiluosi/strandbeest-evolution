#!/usr/bin/env python3
"""Generate asset reference tables and the full assumptions inventory from schemas/*.schema.json (E1-05).

  python scripts/gen_reference_docs.py          # (re)write docs/reference/*.md
  python scripts/gen_reference_docs.py --check  # fail if any generated file in docs/reference/ is stale (CI)
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SCHEMAS = ("design", "scenario", "run", "measurement", "profile", "ops", "scenario-v1")
PRIMARY_ASSUMPTION_SCHEMAS = ("design", "scenario")
HEADER = "<!-- Generated by scripts/gen_reference_docs.py from schemas/. Do not edit by hand; change the schema annotations and regenerate. -->"


@dataclass
class FieldRow:
    schema: str
    path: str
    kind: str
    required: bool
    default: str
    unit: str
    bounds: str
    group: str
    assumption: bool
    source: str
    calibratable: bool
    affects: str
    doc_zh: str
    doc_en: str


def _fmt_val(v: Any) -> str:
    if v is None:
        return "`null`"
    if v == {} or v == []:
        return f"`{json.dumps(v)}`"
    return f"`{json.dumps(v, ensure_ascii=False)}`"


def _type_str(node: dict, defs: dict[str, dict]) -> str:
    if "$ref" in node:
        ref = node["$ref"].split("/")[-1]
        target = defs.get(ref, {})
        if target.get("type") == "object" and "properties" in target:
            return f"`{ref}`"
        return f"`{ref}` ({_type_str(target, defs)})"
    if "const" in node:
        return f"const `{json.dumps(node['const'])}`"
    if "enum" in node:
        return "enum " + " \\| ".join(f"`{json.dumps(v)}`" for v in node["enum"])
    for key in ("oneOf", "anyOf"):
        if key in node:
            return " \\| ".join(_type_str(s, defs) for s in node[key])
    t = node.get("type")
    if isinstance(t, list):
        return " \\| ".join(f"`{x}`" for x in t)
    if t == "array":
        items = node.get("items", {})
        return f"array<{_type_str(items, defs)}>" if isinstance(items, dict) else "array"
    if t == "object":
        ap = node.get("additionalProperties")
        if isinstance(ap, dict) and "properties" not in node:
            return f"map<string, {_type_str(ap, defs)}>"
        return "`object`"
    return f"`{t or 'any'}`"


def _bounds_str(node: dict) -> str:
    parts: list[str] = []
    if "x-range" in node:
        lo, hi = node["x-range"]
        parts.append(f"range `[{lo}, {hi}]`")
    b: list[str] = []
    if "minimum" in node:
        b.append(f"≥ {node['minimum']}")
    if "exclusiveMinimum" in node:
        b.append(f"> {node['exclusiveMinimum']}")
    if "maximum" in node:
        b.append(f"≤ {node['maximum']}")
    if "exclusiveMaximum" in node:
        b.append(f"< {node['exclusiveMaximum']}")
    if b:
        parts.append(", ".join(b))
    return "; ".join(parts) or "–"


def _doc_pair(node: dict) -> tuple[str, str]:
    xd = node.get("x-doc")
    zh = xd.get("zh", "") if isinstance(xd, dict) else ""
    en = (xd.get("en", "") if isinstance(xd, dict) else "") or node.get("description", "")
    return zh.replace("|", "\\|"), en.replace("|", "\\|")


def _merge_ref(node: dict, defs: dict[str, dict]) -> dict:
    if "$ref" not in node:
        return node
    ref_name = node["$ref"].split("/")[-1]
    target = defs.get(ref_name, {})
    merged = dict(target)
    for k, v in node.items():
        if k != "$ref":
            merged[k] = v
    return merged


def collect_fields(schema_name: str, schema: dict) -> list[FieldRow]:
    defs = schema.get("$defs", {})
    rows: list[FieldRow] = []

    def walk_obj(obj_node: dict, prefix: str, seen_refs: set[str]) -> None:
        req = set(obj_node.get("required", []))
        props = obj_node.get("properties", {})
        for key, raw_sub in props.items():
            path = f"{prefix}.{key}" if prefix else key
            ref_name = raw_sub.get("$ref", "").split("/")[-1] if "$ref" in raw_sub else ""
            sub = _merge_ref(raw_sub, defs)
            zh, en = _doc_pair(sub)
            unit = sub.get("x-unit", "")
            if not unit and isinstance(sub.get("additionalProperties"), dict):
                unit = sub["additionalProperties"].get("x-unit", "")
            default = _fmt_val(sub["default"]) if "default" in sub else ("*(required)*" if key in req else "–")
            affects = ", ".join(f"`{a}`" for a in sub.get("x-affects", [])) or "–"
            rows.append(
                FieldRow(
                    schema=schema_name,
                    path=path,
                    kind=_type_str(raw_sub, defs),
                    required=key in req,
                    default=default,
                    unit=f"`{unit}`" if unit else "–",
                    bounds=_bounds_str(sub),
                    group=f"`{sub['x-group']}`" if "x-group" in sub else "–",
                    assumption=bool(sub.get("x-assumption")),
                    source=str(sub.get("x-source", "")).replace("|", "\\|"),
                    calibratable=bool(sub.get("x-calibratable")),
                    affects=affects,
                    doc_zh=zh,
                    doc_en=en,
                )
            )
            if sub.get("type") == "object" and "properties" in sub and (not ref_name or ref_name not in seen_refs):
                walk_obj(sub, path, seen_refs | ({ref_name} if ref_name else set()))
            elif sub.get("type") == "array" and isinstance(sub.get("items"), dict):
                items_raw = sub["items"]
                item_ref = items_raw.get("$ref", "").split("/")[-1] if "$ref" in items_raw else ""
                items = _merge_ref(items_raw, defs)
                if items.get("type") == "object" and "properties" in items and (not item_ref or item_ref not in seen_refs):
                    walk_obj(items, f"{path}[]", seen_refs | ({item_ref} if item_ref else set()))

    if schema.get("type") == "object" and "properties" in schema:
        walk_obj(schema, "", set())
    elif "oneOf" in schema:
        for variant in schema["oneOf"]:
            v_node = _merge_ref(variant, defs)
            tag = v_node.get("properties", {}).get("type", {}).get("const", "op")
            if v_node.get("type") == "object" and "properties" in v_node:
                walk_obj(v_node, f"[{tag}]", set())
    return rows


def render_schema_doc(name: str, schema: dict, rows: list[FieldRow]) -> str:
    title = schema.get("title", name)
    desc = schema.get("description", "")
    assumptions = [r for r in rows if r.assumption]
    calibratable = [r for r in rows if r.calibratable]
    lines = [
        HEADER,
        f"# `{title}` Schema Reference (`schemas/{name}.schema.json`)",
        "",
        f"> {desc}" if desc else f"> Reference for `schemas/{name}.schema.json`.",
        "",
        f"- **Fields documented**: {len(rows)}",
        f"- **Assumed parameters (`x-assumption: true`)**: {len(assumptions)}",
        f"- **Calibratable parameters (`x-calibratable: true`)**: {len(calibratable)}",
        "",
        "## Field Table / 字段总表",
        "",
        "| Path | Type | Default | Unit | Bounds / Range | Flags | 说明 (zh) / Description (en) |",
        "| :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
    ]
    for r in rows:
        flags: list[str] = []
        if r.assumption:
            flags.append("`assumption`")
        if r.calibratable:
            flags.append("`calibratable`")
        if r.group != "–":
            flags.append(r.group)
        if r.affects != "–":
            flags.append(f"affects: {r.affects}")
        flag_str = "<br>".join(flags) if flags else "–"
        doc_parts = [p for p in (r.doc_zh, r.doc_en) if p]
        if r.source:
            doc_parts.append(f"*Source*: {r.source}")
        doc_str = "<br>".join(doc_parts) or "–"
        lines.append(f"| `{r.path}` | {r.kind} | {r.default} | {r.unit} | {r.bounds} | {flag_str} | {doc_str} |")
    lines.append("")
    return "\n".join(lines)


def render_index(all_rows: dict[str, list[FieldRow]]) -> str:
    assumptions = [r for s in PRIMARY_ASSUMPTION_SCHEMAS for r in all_rows.get(s, []) if r.assumption]
    calibratable = [r for s in PRIMARY_ASSUMPTION_SCHEMAS for r in all_rows.get(s, []) if r.calibratable]
    lines = [
        HEADER,
        "# Asset Schema Reference & Assumptions Inventory / 资产参考与假设参数总表",
        "",
        "> Generated automatically from the `x-` property annotations in `schemas/*.schema.json` ([ADR-0007](../adr/0007-property-system-and-plugin-api.md), `E1-05`).",
        "> Run `python scripts/gen_reference_docs.py` to update; CI verifies with `--check`.",
        "",
        "## 1. Asset Schemas / 资产目录",
        "",
        "| Schema | Reference | Fields | Assumptions (`x-assumption`) | Calibratable (`x-calibratable`) |",
        "| :--- | :--- | ---: | ---: | ---: |",
    ]
    for s in SCHEMAS:
        rs = all_rows[s]
        n_a = sum(1 for r in rs if r.assumption)
        n_c = sum(1 for r in rs if r.calibratable)
        lines.append(f"| `schemas/{s}.schema.json` | [{s}.md]({s}.md) | {len(rs)} | {n_a} | {n_c} |")

    lines.extend(
        [
            "",
            "## 2. Assumptions Inventory / 我们到底猜了哪些参数（`x-assumption: true`）",
            "",
            f"Total assumed parameters in `Design` and `Scenario`: **{len(assumptions)}**. Every physical guess is a named field with a documented source and is saved with every `Run`.",
            "",
            "| Schema | Field Path | Default | Unit | Calibratable | Source / Justification (`x-source`) | 说明 (zh) / Description (en) |",
            "| :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
        ]
    )
    for r in assumptions:
        cal = "yes (`calibratable`)" if r.calibratable else "no"
        doc = "<br>".join(p for p in (r.doc_zh, r.doc_en) if p) or "–"
        lines.append(f"| `{r.schema}` | `{r.path}` | {r.default} | {r.unit} | {cal} | {r.source or '–'} | {doc} |")

    lines.extend(
        [
            "",
            "## 3. Calibratable Parameters / 可被实测校准的参数（`x-calibratable: true`）",
            "",
            "| Schema | Field Path | Default | Unit | Range | 说明 (zh) / Description (en) |",
            "| :--- | :--- | :--- | :--- | :--- | :--- |",
        ]
    )
    for r in calibratable:
        doc = "<br>".join(p for p in (r.doc_zh, r.doc_en) if p) or "–"
        lines.append(f"| `{r.schema}` | `{r.path}` | {r.default} | {r.unit} | {r.bounds} | {doc} |")

    lines.append("")
    return "\n".join(lines)


def outputs(schemas_dir: Path, out_dir: Path) -> dict[Path, str]:
    all_rows: dict[str, list[FieldRow]] = {}
    res: dict[Path, str] = {}
    for name in SCHEMAS:
        schema = json.loads((schemas_dir / f"{name}.schema.json").read_text())
        rows = collect_fields(name, schema)
        all_rows[name] = rows
        res[out_dir / f"{name}.md"] = render_schema_doc(name, schema, rows)
    res[out_dir / "README.md"] = render_index(all_rows)
    return res


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--schemas", type=Path, default=ROOT / "schemas")
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "reference")
    args = ap.parse_args(argv)
    files = outputs(args.schemas, args.out)
    stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
    if args.check:
        if stale:
            for p in stale:
                print(f"stale: {p.relative_to(ROOT) if p.is_relative_to(ROOT) else p}")
            print("reference docs are out of date: run python scripts/gen_reference_docs.py")
            return 1
        print(f"ok: {len(files)} reference docs up to date")
        return 0
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    print(f"wrote {len(files)} reference docs to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
