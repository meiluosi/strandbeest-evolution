import { readFileSync } from "node:fs";
import loadMujoco from "@mujoco/mujoco";
import type { Design } from "strandbeest-core";
import { beforeAll, expect, it } from "vitest";
import { buildMjcf, resolveSpec } from "./builder";
import { scenarioFromDesign } from "./from-design";

const design = JSON.parse(
	readFileSync(
		new URL(
			"../../../schemas/examples/design-jansen-small-6leg.json",
			import.meta.url,
		),
		"utf8",
	),
) as Design;
let mj: Awaited<ReturnType<typeof loadMujoco>>;
beforeAll(async () => {
	mj = await loadMujoco();
});

// An independent one-DOF contact oracle, not a trajectory generated by the
// Python walker. With constant impedance and no other forces, native contact
// acceleration must satisfy x'' + 2*zeta*sqrt(k)*x' + k*x = 0.
it.each(
	[0.05, 0.5, 50].flatMap((mass) => [0.5, 1, 2].map((ratio) => [mass, ratio])),
)(
	"requested damping ratio is independent of walker mass (%s kg, %s)",
	(mass, ratio) => {
		const stiffness = 40000;
		const cfg = scenarioFromDesign(design, {
			walker: { body_mass: mass },
			solver: { contact_stiffness: stiffness, contact_damping_ratio: ratio },
		});
		const { xml } = buildMjcf(cfg, resolveSpec(cfg));
		const reference = /<default>[\s\S]*?<geom[^>]*solref="([^"]+)"/.exec(
			xml,
		)?.[1];
		expect(reference).toBeDefined();
		for (const probeMass of [0.02, 2]) {
			const model: any = mj.MjModel.from_xml_string(`<mujoco>
		  <option timestep=".00001" gravity="0 0 0" solver="Newton" tolerance="1e-12"/>
		  <default><geom solref="${reference}" solimp=".9 .9 .001 .5 2" condim="1"/></default>
		  <worldbody><geom type="plane" size="1 1 .1"/><body pos="0 0 .048">
		    <joint type="slide" axis="0 0 1"/><geom type="sphere" size=".05" mass="${probeMass}"/>
		  </body></worldbody></mujoco>`);
			const data: any = new mj.MjData(model);
			try {
				data.qvel[0] = 0.01;
				mj.mj_forward(model, data);
				expect(data.ncon).toBe(1);
				const expected =
					stiffness * 0.002 -
					2 * (ratio as number) * Math.sqrt(stiffness) * 0.01;
				expect(Math.abs(data.qacc[0] - expected)).toBeLessThan(2e-10);
			} finally {
				data.delete();
				model.delete();
			}
		}
	},
);
